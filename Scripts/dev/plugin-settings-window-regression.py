#!/usr/bin/env python3
"""Captured Main windows: native pages, independent files and cold consumers."""
from fixture_receipts import receipt_run, stage_receipt
import argparse
from copy import deepcopy
import fcntl
import hashlib
import importlib.util
import json
import os
import re
from pathlib import Path
import shutil

from guest_profile import activate_profile, profile_argument

spec = importlib.util.spec_from_file_location('window_runner', Path(__file__).with_name('plugin-settings-host-assets-regression.py'))
runner = importlib.util.module_from_spec(spec); spec.loader.exec_module(runner)
MEMBERS = ('wallcards', 'somnus')


def hashes(case):
    return {str(p.relative_to(case)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((case / 'config').rglob('*.json'))}


@receipt_run
def run(args, profile, plugin, scope):
    case, out = args.work_root / (plugin + '-' + scope), args.output / (plugin + '-' + scope)
    case.mkdir(); out.mkdir(); (out / 'persisted').mkdir()
    install = case / 'install'
    # Source files are read-only inputs. Only the root fixture and .qmlls.ini are
    # generated by run_fixture; keep those private instead of copying 7900 inodes.
    assert not (args.source / 'plugin-settings-window-native.qml').exists()
    shutil.copytree(args.source, install, copy_function=os.link, ignore=shutil.ignore_patterns('.git', '.envrc', '__pycache__', '.qmlls.ini'))
    for part in ('config/settings/plugins', 'cache', 'state', 'home', 'wallpapers'):
        (case / part).mkdir(parents=True)
    dest = case / ('config/plugins/' + plugin); shutil.copytree(args.plugins / plugin, dest)
    wall = plugin == 'wallcards'; field = 'card_height' if wall else 'buttonWidth'
    shared = dict(opaque=dict(keep='shared'))
    shared.update(dict(card_height=300, animate_window=False, live_preview=False, background_color='#000000', background_opacity=0.5) if wall else dict(buttonWidth=300, animationsEnabled=False, lockOnSuspend=True))
    overrides = dict(opaque=dict(keep='selected'))
    if not wall:
        overrides['lockOnSuspend'] = False
    bar = dict(widgets=dict(left=[dict(id='plugin:' + plugin, instanceSettings=overrides), dict(id='plugin:' + plugin, instanceSettings={field: 400}), dict(id='plugin:' + plugin, instanceSettings=dict(opaque=dict(keep='inherited')))]))
    initial = dict(shared=shared, bar=bar); edited = deepcopy(initial)
    (edited['shared'] if scope == 'shared' else edited['bar']['widgets']['left'][0]['instanceSettings'])[field] = 400
    reset = deepcopy(edited); (reset['shared'] if scope == 'shared' else reset['bar']['widgets']['left'][0]['instanceSettings']).pop(field)
    following = deepcopy(reset); following['shared'][field] = 400
    expected = dict(initial=initial, discarded=initial, edited=edited, **{'reset-staged': edited}, reset=reset, following=following)
    if wall:
        writer = deepcopy(following); writer['bar']['widgets']['left'][0]['instanceSettings'][field] = 410
        expected['writer'] = writer
    for path, data in [('input.json', dict(plugin=plugin)), ('expectations.json', expected), ('config/settings.json', dict(settingsVersion=62)), ('config/settings/wallpaper.json', dict(directory=str(case / 'wallpapers'))), ('config/plugins.json', dict(version=6, states={}, sources=[])), ('config/settings/plugins/' + plugin + '.json', shared), ('config/settings/bar.json', bar)]:
        runner.write_json(case / path, data)
    # Only the compositor collaborator is replaced, in the disposable plugin copy.
    # Production action dispatch and the entire window body remain unchanged.
    if not wall:
        window = dest / 'SomnusWindow.qml'; source = window.read_text()
        if source.count('import qs.Services.Compositor') != 1:
            raise RuntimeError('review inert compositor import boundary')
        window.write_text(source.replace('import qs.Services.Compositor', 'import "controlled"'))
        controlled = dest / 'controlled'; controlled.mkdir()
        (controlled / 'qmldir').write_text('singleton CompositorService 1.0 CompositorService.qml\n')
        shutil.copy2(args.source / 'Scripts/dev/fixtures/plugin-settings-window-compositor.qml', controlled / 'CompositorService.qml')
    wanted = None
    if args.negative_control:
        path = dest / ('BarWidget.qml' if args.negative_control == 'opener' else ('Wallcards.qml' if wall else 'SomnusWindow.qml') if args.negative_control in ('writer', 'child') else 'Main.qml')
        old, new = (('toggle(root.pluginApi, root.screen)', 'toggle(root.pluginApi.base, root.screen)') if wall else ('togglePanel?.(screen, pluginApi)', 'togglePanel?.(screen, pluginApi.base)')) if args.negative_control == 'opener' else ('"pluginApi": caller', '"pluginApi": root.pluginApi') if args.negative_control == 'window' else ('onWindowCurrentChanged: if (windowApi && !windowCurrent)', 'onWindowCurrentChanged: if (false)')
        if args.negative_control == 'writer':
            old, new = 'const api = root.pluginApi;', 'const api = root.pluginApi.base;'
        elif args.negative_control == 'child':
            old, new = ('height: root.cardHeight', 'height: root.cardHeight + 13') if wall else ('width: btnW', 'width: btnW + 13')
        source = path.read_text()
        if source.count(old) != 1:
            raise RuntimeError('stale window mutation: ' + old)
        path.write_text(source.replace(old, new)); wanted = 'captured originating window API' if args.negative_control != 'retirement' else 'retired context unloads its window'
        if args.negative_control == 'writer': wanted = 'independent complete window readback: writer'
        if args.negative_control == 'child': wanted = 'actual card/button child geometry'
    if args.old_red:
        wanted = 'captured originating window API'
    env = dict(PHA_WINDOW_PLUGIN=plugin, PHA_WINDOW_SCOPE=scope, PHA_WINDOW_CASE=str(case), PHA_WINDOW_OUTPUT=str(out), PHA_WINDOW_DISK=str(args.source / 'Scripts/dev/fixtures/plugin-settings-query-disk.py'), PHA_WINDOW_OLD_RED='1' if args.old_red else '0', HOME=str(case / 'home'))
    sequence = [('edit', ''), ('cold', 'edited'), ('reset', ''), ('cold', 'reset'), ('follow', ''), ('cold', 'following')]
    if wall and not args.old_red and args.negative_control in (None, 'writer'):
        sequence += [('writer', ''), ('cold', 'writer')]
    for mode, boundary in sequence:
        output = out / (mode + ('-' + boundary if boundary else '')); output.mkdir(); before = hashes(case)
        try:
            text = runner.run_fixture(profile, install, case, output, args.source / 'Scripts/dev/fixtures/plugin-settings-window-native.qml', extra_env=dict(env, PHA_WINDOW_MODE=mode, PHA_WINDOW_BOUNDARY=boundary), extra_lint=tuple(sorted(dest.rglob('*.qml'))), timeout=90)
        except RuntimeError:
            if not wanted or not (output / 'runtime.log').is_file() or wanted not in (output / 'runtime.log').read_text() or (output / 'runtime.exit').read_text().strip() != '2':
                raise
            if args.old_red and not (out / 'persisted/edited.json').is_file():
                raise RuntimeError('original window red did not reach native publication')
            result = dict(status='PASS', kind='original-window-red' if args.old_red else 'rejecting-control', rejectedAt=wanted, completePlanAcceptance=False)
            stage_receipt(out / 'result.json', result); runner.remove_completed_installs(case, out); return result
        marker = 'WINDOW_NATIVE: PASS ' + plugin + ' ' + scope + ' ' + mode
        if marker not in text or any(key in text for key in ('TypeError:', 'ReferenceError:', 'SyntaxError:', 'Binding loop detected', 'WINDOW_NATIVE_ASSERT:')):
            raise RuntimeError('window consumer/diagnostic failure')
        if mode == 'cold' and hashes(case) != before:
            raise RuntimeError('cold window published configuration')
        if not wall:
            actions = re.findall(r'WINDOW_ACTION (\w+)', text)
            expected_actions = ['lockAndSuspend', 'suspend', 'lockAndSuspend', 'lockAndSuspend']
            if mode in ('edit', 'reset', 'follow'):
                expected_actions *= 2
            if actions != expected_actions:
                raise RuntimeError('actual inert compositor action targets differ: ' + repr(actions))
        stage_receipt(output / 'observed.json', dict(status='PASS', configurationHashes=hashes(case)))
    if wanted:
        raise RuntimeError('window control escaped')
    for boundary, data in expected.items():
        if json.loads((out / ('persisted/' + boundary + '.json')).read_text()) != dict(status='PASS', values=data):
            raise RuntimeError('complete window documents differ')
    result = dict(status='PASS', plugin=plugin, scope=scope, independentBoundaries=sorted(expected), unchangedHashColdReaders=['edited', 'reset', 'following'] + (['writer'] if wall else []), physicalProof=False, completePlanAcceptance=False)
    stage_receipt(out / 'result.json', result); runner.remove_completed_installs(case, out)
    print('WINDOW_NATIVE ' + plugin + '/' + scope + ': PASS', flush=True); return result


@receipt_run
def main():
    parser = argparse.ArgumentParser(description=__doc__); profile_argument(parser)
    for key in ('source', 'plugins', 'work-root', 'output'):
        parser.add_argument('--' + key, type=Path, required=True)
    parser.add_argument('--plugin', choices=MEMBERS); parser.add_argument('--scope', choices=('shared', 'instance'))
    oracle = parser.add_mutually_exclusive_group()
    oracle.add_argument('--old-red', action='store_true')
    oracle.add_argument('--negative-control', choices=('opener', 'window', 'retirement', 'writer', 'child'))
    args = parser.parse_args(); profile = activate_profile(args.guest_profile); profile.prepare_roots()
    if Path(__file__).resolve() != args.source.resolve() / 'Scripts/dev/plugin-settings-window-regression.py':
        parser.error('execute supplied source')
    if (args.old_red or args.negative_control) and (not args.plugin or args.scope != 'instance'):
        parser.error('control requires explicit instance member')
    if args.negative_control == 'writer' and args.plugin != 'wallcards':
        parser.error('layout writer belongs to Wallcards')
    for path, parent in ((args.work_root, profile.work_base), (args.output, profile.journal_base)):
        if path != path.resolve() or path == parent or not path.is_relative_to(parent):
            parser.error('fresh owned profile roots required')
    with (profile.work_base / '.plugin-settings-host-assets.lock').open('a+') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB); args.work_root.mkdir(); args.output.mkdir()
        paths = [Path(__file__), args.source / 'Scripts/dev/fixtures/plugin-settings-window-native.qml', args.source / 'Scripts/dev/fixtures/plugin-settings-window-compositor.qml', args.source / 'Scripts/dev/fixtures/plugin-settings-query-disk.py']
        runner.write_json(args.output / 'inputs.json', dict(source=str(args.source), plugins=str(args.plugins), files={str(p.relative_to(args.source)): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}, pluginFiles={str(p.relative_to(args.plugins)): hashlib.sha256(p.read_bytes()).hexdigest() for member in ((args.plugin,) if args.plugin else MEMBERS) for p in (args.plugins / member).rglob('*') if p.is_file()}))
        results = [run(args, profile, plugin, scope) for plugin in ((args.plugin,) if args.plugin else MEMBERS) for scope in ((args.scope,) if args.scope else ('instance', 'shared'))]
        stage_receipt(args.output / 'result.json', dict(status='PASS', cases=results, completePlanAcceptance=False))


if __name__ == '__main__':
    main()
